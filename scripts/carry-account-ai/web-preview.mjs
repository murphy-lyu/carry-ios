function format(value, label, lang, key) {
  if (value === undefined || value === null || value === "") return "—";
  if (typeof value === "boolean") return value ? label.yes : label.no;
  if (Array.isArray(value))
    return value.map((v) => format(v, label, lang, key)).join(" · ");
  if (typeof value === "object")
    return `${label.files} · ${Object.keys(value).length}`;
  if (typeof value === "number") {
    if (/(?:LocalMinutes|StartMinutes|InMinutes|OutMinutes)$/.test(key))
      return value < 0
        ? "—"
        : `${String(Math.floor(value / 60)).padStart(2, "0")}:${String(value % 60).padStart(2, "0")}`;
    if (key === "stayMinutes") return new Intl.NumberFormat(lang, {
      style: "unit", unit: "minute", unitDisplay: "short",
    }).format(value);
    return new Intl.NumberFormat(lang).format(value);
  }
  if (
    [
      "reminderConfigData",
      "additionalDestinationsData",
      "backgroundsData",
    ].includes(key)
  ) {
    try {
      const parsed = JSON.parse(value);
      if (Array.isArray(parsed))
        return parsed
          .map((v) =>
            typeof v === "string" ? v : (v.city ?? v.name ?? label.details),
          )
          .join(" · ");
      return label.settings;
    } catch {
      return label.details;
    }
  }
  if (/Date$|timestamp/.test(key)) {
    const date = new Date(value);
    if (Number.isFinite(date.getTime()))
      return new Intl.DateTimeFormat(lang, {
        dateStyle: "medium",
        timeZone: "UTC",
      }).format(date);
  }
  return String(value);
}
